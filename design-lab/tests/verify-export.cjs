const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const XLSX = require('@e965/xlsx');
const model = require('../model.js');
const jsonFile = path.join(__dirname,'../evidence/export-calm.json');
const xlsxFile = path.join(__dirname,'../evidence/export-calm.xlsx');
const payload = JSON.parse(fs.readFileSync(jsonFile,'utf8'));
const data = model.restore(payload);
const workbook = XLSX.readFile(xlsxFile);
assert.deepEqual(workbook.SheetNames,['Измерения','Замеры','Периоды']);
const sheets = workbook.SheetNames.map(name=>XLSX.utils.sheet_to_json(workbook.Sheets[name],{header:1}));
assert.equal(sheets[0].length-1,data.sessions.length);
assert.equal(sheets[1].length-1,data.sessions.flatMap(s=>s.readings).length);
assert.equal(sheets[2].length-1,data.phases.length);
assert.ok(sheets[0].some(row=>row.includes('Заметка изменена и сохранена')));
assert.ok(sheets[1].some(row=>row[2].includes('12:53')));
assert.ok(workbook.Sheets['Измерения']['!autofilter']);
process.stdout.write(JSON.stringify({sessions:data.sessions.length,readings:sheets[1].length-1,phases:data.phases.length,sheets:workbook.SheetNames})+'\n');
